"""Write docs/date_slip.md from docs/date_slip_summary.json + docs/date_slip_check.json (card 19).
Headline sentences are built from the numbers only.

    node pipeline/date_slip.mjs && python pipeline/date_slip_doc.py
"""
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    s = json.loads((ROOT / "docs" / "date_slip_summary.json").read_text(encoding="utf-8"))
    chk_path = ROOT / "docs" / "date_slip_check.json"
    chk = json.loads(chk_path.read_text(encoding="utf-8")) if chk_path.exists() else {}
    sites = s["sites"]
    from datetime import date
    n_land = (date.fromisoformat(s['last_landing']) - date.fromisoformat(s['first_landing'])).days + 1
    d14 = {x["id"]: x["slip"]["+14d"] for x in sites}
    d7 = {x["id"]: x["slip"]["+7d"] for x in sites}
    by = {x["id"]: x for x in sites}

    # ---- headlines (numbers only)
    H = []
    flip = [i for i in d14 if d14[i]["longest_dark_h"]["worst_change"] >= 300]
    mx = max(d14[i]["longest_dark_h"]["worst_change"] for i in d14)
    H.append(f"At {len(flip)} of {len(sites)} sites, a 14-day slip can turn the first two weeks on the surface from "
             f"daylight into night: the longest darkness grows by up to {mx:.0f} h.")
    if "ARTEMIS_HAWORTH" in d14:
        h14, h7 = d14["ARTEMIS_HAWORTH"], d7["ARTEMIS_HAWORTH"]
        H.append(f"At ARTEMIS_HAWORTH a 14-day slip changes the longest darkness by up to "
                 f"{h14['longest_dark_h']['worst_change']:.0f} h and a 7-day slip by up to {h7['longest_dark_h']['worst_change']:.0f} h; "
                 f"the share of time with both sunlight and an Earth link can drop by {-h14['both_frac']['worst_change']:.0f} percentage points.")
    tol = min(d14, key=lambda i: d14[i]["longest_dark_h"]["worst_change"])
    H.append(f"{tol} is the most slip-tolerant site: even in the worst case a 14-day slip adds only "
             f"{d14[tol]['longest_dark_h']['worst_change']:.0f} h to the longest darkness.")
    med7 = statistics.median(d7[i]["sun_frac"]["median_abs_change"] for i in d7)
    med14 = statistics.median(d14[i]["sun_frac"]["median_abs_change"] for i in d14)
    H.append(f"For a typical landing day, sunlight in the first two weeks changes by a median of {med7:.0f} percentage "
             f"points after a 7-day slip and {med14:.0f} after a 14-day slip (median over all {len(sites)} sites).")
    far = [x["id"] for x in sites if x["range"]["earth_frac"][1] == 0]
    if far:
        H.append(f"No landing date helps the Earth link at {', '.join(far)}: the Earth is never above the horizon there, "
                 "so a direct link is impossible on every date.")

    L = ["# Landing-date slips: how much changes if the landing moves 1–2 weeks? (card 19)\n",
         "Generated by `node pipeline/date_slip.mjs` + `python pipeline/date_slip_doc.py`. Per-site data: "
         "`web/data/date_slip/<ID>.json` (contract section 15, proposal). Summary: `docs/date_slip_summary.json`.\n",
         f"**Method.** Every landing day {s['first_landing']} … {s['last_landing']} (00:00 UTC, {n_land} days), "
         f"metrics over the first {s['days_after_landing']} days after landing, hourly, with the actual `web/js/core.js` "
         "definitions (sunlit = ≥ 50 % of the solar disc above the real terrain horizon; Earth = Earth centre above it; both = "
         "both at once; longest dark = longest run of not-sunlit hours). Best / worst = highest / lowest *both* (ties: shorter "
         "longest dark), the same ranking as the app's landing-date scan. Slip change = metric(landing + 7 or 14 days) − "
         "metric(landing) over every landing day; *median* = median absolute change, *worst* = the most unfavourable change.\n",
         "## Headlines (generated from the numbers)\n"]
    L += [f"{k}. {h}" for k, h in enumerate(H, 1)]
    L += ["", "## Per site\n",
          "| Site | Best landing (both %, longest dark h) | Worst landing (both %, longest dark h) | +7 d: median / worst Δ sunlight (pp) | +7 d worst Δ longest dark (h) | +14 d: median / worst Δ sunlight (pp) | +14 d worst Δ longest dark (h) | +14 d worst Δ both (pp) |",
          "|---|---|---|---|---|---|---|---|"]
    for x in sites:
        b, w, a7, a14 = x["best"], x["worst"], x["slip"]["+7d"], x["slip"]["+14d"]
        L.append(f"| {x['id']} | {b['landing']} ({b['both_frac'] * 100:.0f} %, {b['longest_dark_h']}) | "
                 f"{w['landing']} ({w['both_frac'] * 100:.0f} %, {w['longest_dark_h']}) | "
                 f"{a7['sun_frac']['median_abs_change']:.1f} / {a7['sun_frac']['worst_change']:.1f} | {a7['longest_dark_h']['worst_change']:.0f} | "
                 f"{a14['sun_frac']['median_abs_change']:.1f} / {a14['sun_frac']['worst_change']:.1f} | {a14['longest_dark_h']['worst_change']:.0f} | "
                 f"{a14['both_frac']['worst_change']:.1f} |")
    L += ["", "## Verification\n"]
    ic, ap = chk.get("independent_cells"), chk.get("app_cells")
    if ic:
        L.append(f"- Independent loop over `ephem.bin` + horizon files (no `core.js`, `pipeline/verify_date_slip.py`, seed {ic['seed']}): "
                 f"{sum(c['match_4dp'] for c in ic['cells'])}/{ic['n']} random (site, landing day) cells match to 4 decimals.")
    if ap:
        L.append(f"- App cross-check (`pipeline/verify_date_slip_app.mjs`, actual `core.metrics` for the same 14-day period): "
                 + ", ".join(f"{c['id']} {c['landing']} {'match' if c['match_4dp'] else 'DIFF'}" for c in ap["cells"]) + ".")
    L += ["- Details: `docs/date_slip_check.json`.", "",
          "## Limits",
          "- Landing at 00:00 UTC of each day; a landing later in the day shifts every number slightly.",
          "- Geometry only: terrain horizons from LOLA (cards 8/9), no link budget, no lander power model.",
          "- Ephemeris window 2026–2030; landing days are limited to 2026–2027 so every 14-day window is inside it.", ""]
    (ROOT / "docs" / "date_slip.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(H))


if __name__ == "__main__":
    main()
