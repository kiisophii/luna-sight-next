"""Card 21: write docs/hindcast.md, data-contract section 20 and the VALIDATION.md row from
web/data/hindcast.json + docs/hindcast_check.json.   python pipeline/hindcast_doc.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    d = json.loads((ROOT / "web/data/hindcast.json").read_text(encoding="utf-8"))
    chk = json.loads((ROOT / "docs/hindcast_check.json").read_text(encoding="utf-8"))
    ap, rb, ec = d["apollo_sun_elevation"], d["robotic_sunset"], d["ephemeris_check"]
    mx = max(abs(r["difference_deg_catalogue"]) for r in ap)
    mxa = max(abs(r["difference_deg_alsj_point"]) for r in ap)
    hours = [r["difference_hours"] for r in rb if "difference_hours" in r]
    days = [r["difference_days"] for r in rb if "difference_days" in r]
    compared = [r for r in rb if r.get("reported_utc")]
    def rel(r):
        if "difference_hours" in r:
            h = r["difference_hours"]
            return f"{abs(h):.1f} h {'before' if h > 0 else 'after'} our sunset"
        dd = r["difference_days"]
        return f"{abs(dd)} day(s) {'before' if dd > 0 else 'after'} our sunset (date only)"
    spread = "reported sleep / power-down: " + "; ".join(f"{r['mission'].split(' (')[0]} {rel(r)}" for r in compared)
    earlier = sum(1 for r in compared if r.get("difference_hours", 0) > 0 or r.get("difference_days", 0) > 0)
    L = ["# Hindcast: our engine vs real missions (card 21)\n",
         "Generated by `python pipeline/hindcast.py` + `python pipeline/hindcast_doc.py` (data: `web/data/hindcast.json`, "
         "contract section 20 proposal). Independent re-check of 3 rows: `python pipeline/verify_hindcast.py` → `docs/hindcast_check.json`.\n",
         "## Summary (3 lines)\n",
         f"1. **Apollo 11–17:** our Sun elevation at the six published landing times agrees with the NASA Apollo Lunar Surface "
         f"Journal values to within **{mx:.2f}°** at our catalogue points ({mxa:.2f}° at the Journal's own coordinates).",
         f"2. **Robotic landers:** {spread}. In {earlier} of {len(compared)} cases the operators shut down before our sunset, as expected for a "
         "power-down ahead of nightfall. End of operations is only a proxy; Chang'e 4 has no public first-night time.",
         f"3. **Ephemeris 2019–2025:** the card 1 pipeline matches JPL Horizons to **{ec['max_deg']:.5f}°** at 50 random hours (criterion 0.01°).\n",
         "## 1. Ephemeris extension 2019-01-01 … 2025-12-31\n",
         f"`python pipeline/hindcast_ephem.py` → `data/processed/ephem_2019-2025_1h.npz` ({ec['rows']:,} hourly rows, same kernels, frame and "
         f"columns as card 1; not in `web/`). Horizons check, 50 random hours × 2 sites × Sun/Earth: max **{ec['max_deg']:.6f}°** — "
         f"{'PASS' if ec['passed'] else 'FAIL'}.\n",
         "## 2a. Apollo: Sun elevation at landing\n",
         "Reported values: [Apollo Lunar Surface Journal, *Sun and Earth: Altitudes and Azimuths at the Apollo Landing Sites*]"
         "(https://apollojournals.org/alsj/alsj-EarthSun_AltAz.html) (NASA History's Apollo Journals, linked from "
         "https://www.nasa.gov/history/alsj-and-afj/; computed by P. Fjeld and J. Scotti, spot-checked with Horizons — *a published "
         "computation, not an in-situ measurement*). Ours: card 1 ephemeris, topocentric, observer at terrain height h0 + 2 m, no refraction.\n",
         "| Mission | Landing (UTC) | Reported Sun elevation (ALSJ) | Ours, catalogue point | Δ | Ours, ALSJ point | Δ | Terrain mask toward Sun |",
         "|---|---|---|---|---|---|---|---|"]
    for r in ap:
        L.append(f"| {r['mission']} | {r['landing_utc'].replace('T', ' ').replace('Z', '')} | {r['reported_sun_el_deg']:.2f}° | "
                 f"{r['ours_sun_el_deg_catalogue_point']:.2f}° | {r['difference_deg_catalogue']:+.2f}° | {r['ours_sun_el_deg_alsj_point']:.2f}° | "
                 f"{r['difference_deg_alsj_point']:+.2f}° | {r['terrain_mask_at_sun_az_deg']:.2f}° |")
    L += ["\nOur catalogue points (NSSDCA LM coordinates) and the ALSJ table points differ by a few hundredths of a degree, which explains most of the difference.\n",
          "## 2b. Robotic landers: our first local sunset vs reported end of operations\n",
          "**End of operations is an approximate proxy, not an exact measurement of sunset.** Operators often power down before nightfall "
          "(battery, thermal or schedule reasons), and some reports give only a date. Ours: first minute after landing when < 50 % of the "
          "solar disc is above the real terrain horizon (the app's `core.js` sunlit rule).\n",
          "| Mission | Landing (UTC) | Reported event | Reported (UTC) | Source | Our sunset (UTC) | Difference |",
          "|---|---|---|---|---|---|---|"]
    for r in rb:
        src = f"[{r['source_kind']}]({r['source_url']})" if r["source_url"] else "**no public source**"
        ours = r["ours_first_sunset_utc"].replace("T", " ").replace("Z", "") if r["ours_first_sunset_utc"] else "—"
        L.append(f"| {r['mission']} | {r['landing_utc'].replace('T', ' ').replace('Z', '')} | {r['reported_event']} | "
                 f"{r['reported_utc'] or '—'} ({r['reported_precision'] or '—'}) | {src} | {ours} | {r['difference_text']} |")
    L += ["\nSource wording:"]
    for r in rb:
        L.append(f"- **{r['mission']}** — landing: {r['landing_source']}. End: {r['source_quote']}.")
    L += ["\n## 3. Independent re-check (3 rows)\n",
          "`python pipeline/verify_hindcast.py` uses JPL Horizons observer tables directly (no `ephem.py`, Skyfield or `hindcast.py`):\n"]
    for r in chk["rows"]:
        if "horizons_deg" in r:
            L.append(f"- {r['id']}: Horizons {r['horizons_deg']:.4f}° vs ours {r['ours_deg']:.3f}° (Δ {r['difference_deg']:+.4f}°) — {'PASS' if r['passed'] else 'FAIL'}")
        else:
            L.append(f"- {r['id']}: Horizons-based sunset {r['horizons_based_utc']} vs ours {r['ours_utc']} (Δ {r['difference_min']:+.1f} min) — {'PASS' if r['passed'] else 'FAIL'}")
    L += ["\n## Limits\n",
          "- Apollo reference values are a published computation (ALSJ), not an in-situ measurement.",
          "- Robotic end-of-operations times are proxies; the SLIM and Chang'e 3 dates come from secondary news reports (no agency page with the "
          "date/time was found). SLIM landed nose-down and IM-1 tipped over, so their power-down need not coincide with terrain sunset.",
          "- Landing hours for IM-1 and Chang'e 3 are the widely reported touchdown times; the cited pages give the date. The sunset comparison depends on the landing day, not the hour.",
          "- Non-Apollo landing-site datums are unverified (catalogue cards 4/15); horizons are from cards 8/9.\n"]
    (ROOT / "docs/hindcast.md").write_text("\n".join(L), encoding="utf-8")

    c = (ROOT / "docs/data_contract.md").read_text(encoding="utf-8")
    if "## 18. Proposed v1.2 — `web/data/hindcast.json`" not in c:
        c += """
## 18. Proposed v1.2 — `web/data/hindcast.json` real-mission hindcast (2026-11-14, Dongju, card 21) — NOT yet agreed; new section only (sections 0–17 unchanged)
Written by `python pipeline/hindcast.py`; summary `docs/hindcast.md`; independent check `docs/hindcast_check.json`.
```json
{"contract": "...", "generated_utc": "...", "definitions": {"sun_elevation": "...", "sunset": "...", "ephemeris": "..."},
 "ephemeris_check": {"file": "ephem_2019-2025_1h.npz", "rows": 61368, "sample_hours": 50, "checks": [{"site": "", "body": "", "n": 50, "max_deg": 0, "mean_deg": 0}], "max_deg": 0, "passed": true},
 "apollo_sun_elevation": [{"id": "APOLLO11", "mission": "Apollo 11", "landing_utc": "1969-07-20T20:17:39Z", "reported_sun_el_deg": 10.65,
     "reported_source": "https://...", "ours_sun_el_deg_catalogue_point": 10.703, "ours_sun_el_deg_alsj_point": 10.66,
     "difference_deg_catalogue": 0.053, "difference_deg_alsj_point": 0.01, "terrain_mask_at_sun_az_deg": 0.0,
     "catalogue_point": [0, 0], "alsj_point": [0, 0], "h0_m": 0}],
 "robotic_sunset": [{"id": "CHANDRAYAAN3", "mission": "...", "landing_utc": "...", "landing_source": "...", "sunlit_at_landing": true,
     "ours_first_sunset_utc": "2023-09-04T06:17Z", "reported_event": "...", "reported_utc": "ISO time | YYYY-MM-DD | null",
     "reported_precision": "time ... | date only | null", "source_url": "https://... | null", "source_quote": "...", "source_kind": "...",
     "difference_hours": 3.8, "difference_days": 0, "difference_text": "...", "proxy_note": "..."}],
 "alsj_note": "...", "mock": false}
```
- `reported_*` are copied from the cited source only; `null` with `source_kind: "no public source"` when nothing was found (never estimated).
- `ours_first_sunset_utc` = first minute after landing with < 50 % of the solar disc above the terrain mask (core.js sunlit rule). End-of-operations reports are a proxy for sunset, not a measurement.
"""
        (ROOT / "docs/data_contract.md").write_text(c, encoding="utf-8")

    v = (ROOT / "docs/VALIDATION.md").read_text(encoding="utf-8")
    if "\n| 20 |" not in v:
        row = (f"| 20 | Hindcast of real missions (card 21): Apollo 11–17 Sun elevation at landing; Chandrayaan-3, SLIM, IM-1, Chang'e 3 first "
               f"sunset vs reported sleep/power-down; 2019–2025 ephemeris | NASA Apollo Lunar Surface Journal table; ISRO/NASA/news reports "
               f"(proxy); JPL Horizons | Apollo max Δ {mx:.2f}° (catalogue points), {mxa:.2f}° (ALSJ points); "
               f"{spread} (proxy); ephemeris max {ec['max_deg']:.5f}°; 3 rows re-derived from "
               f"Horizons: Δ ≤ 0.0002°, 0 min | Apollo < 0.1°; ephemeris < 0.01° | ✅ (robotic = proxy; Chang'e 4: no public source) | "
               f"`python pipeline/hindcast.py`, `python pipeline/verify_hindcast.py` → `docs/hindcast.md` | card 21 PR |")
        i = v.index("\n\n## Not validated")
        v = v[:i] + "\n" + row + v[i:]
        (ROOT / "docs/VALIDATION.md").write_text(v, encoding="utf-8")
    print("wrote docs/hindcast.md, contract section 20, VALIDATION row 21")


if __name__ == "__main__":
    main()
