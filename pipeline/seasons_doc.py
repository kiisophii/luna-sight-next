"""Write docs/seasons.md from docs/seasons_summary.json + web/data/monthly/ + web/data/ephem.bin (numbers only from data).

  python pipeline/seasons_doc.py
"""
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "web" / "data"
T0 = datetime(2026, 1, 1, tzinfo=timezone.utc)


def pct(x):
    return f"{100 * x:.1f}%"


def solstices(lat):
    """Hours of the extreme subsolar latitude, one per half-cycle (local extremum within +-120 days)."""
    w = 120 * 24
    out = []
    for kind, f in (("south", np.argmin), ("north", np.argmax)):
        i = 0
        while i < len(lat):
            j = i + int(f(lat[i:i + 2 * w]))
            a, b = max(0, j - w), min(len(lat), j + w)
            if j == a + int(f(lat[a:b])) and 0 < j < len(lat) - 1:
                if not out or all(abs(j - o[1]) > 24 for o in out):
                    out.append((kind, j, float(lat[j])))
            i = j + w
    return sorted(out, key=lambda o: o[1])


def main():
    S = json.loads((ROOT / "docs" / "seasons_summary.json").read_text())
    chk = json.loads((ROOT / "docs" / "seasons_check.json").read_text())
    meta = json.loads((DATA / "ephem.json").read_text())
    eph = np.fromfile(DATA / "ephem.bin", dtype="<f4").astype(np.float64).reshape(meta["n"], 6)
    lat = np.degrees(np.arcsin(eph[:, 2] / np.linalg.norm(eph[:, :3], axis=1)))
    sm = np.convolve(lat, np.ones(709) / 709, mode="valid")   # 709 h running mean removes the monthly wobble
    sol = [(k, j + 354, v) for k, j, v in solstices(sm)]
    months = S["months"]
    smin, smax = S["subsolar_lat_deg"]["min"], S["subsolar_lat_deg"]["max"]
    mid = [(a + b) / 2 for a, b in zip(smin, smax)]
    south = [k for k, m in enumerate(mid) if m <= -1.0]   # Sun clearly south of the lunar equator
    north = [k for k, m in enumerate(mid) if m >= 1.0]

    rows, eq = [], []
    for s in S["sites"]:
        rec = json.loads((DATA / "monthly" / f"{s['id']}.json").read_text())
        L = rec["lunation"]["sun_frac"]
        ser = rec["series"]
        dS = np.mean([L[k] for k in south]) - np.mean([L[k] for k in north])
        kb, kw = int(np.argmax(ser["sun_frac"])), int(np.argmin(ser["sun_frac"]))
        r = dict(id=s["id"], lat=s["lat"], lmin=min(L), lmax=max(L), dS=dS, best=months[kb], bv=ser["sun_frac"][kb],
                 worst=months[kw], wv=ser["sun_frac"][kw], dmin=min(ser["longest_dark_h"]), dmax=max(ser["longest_dark_h"]),
                 emin=min(rec["lunation"]["earth_frac"]), emax=max(rec["lunation"]["earth_frac"]),
                 cmin=min(ser["sun_frac"]), cmax=max(ser["sun_frac"]))
        rows.append(r)
        if abs(s["lat"]) < 30:
            eq.append(r)
    polar = sorted([r for r in rows if r["lat"] <= -80], key=lambda r: -(r["lmax"] - r["lmin"]))
    eq_span = max(r["lmax"] - r["lmin"] for r in eq)
    eq_cal = max(r["cmax"] - r["cmin"] for r in eq)
    gaps = [(b[1] - a[1]) / 24 for a, b in zip([o for o in sol if o[0] == "south"], [o for o in sol if o[0] == "south"][1:])]

    L = []
    L.append("# Seasons 2026–2030 (monthly metrics)\n")
    L.append("Generated by `python pipeline/seasons_doc.py` from `web/data/monthly/<ID>.json` (written by "
             "`node pipeline/seasons.mjs`, which runs the actual `web/js/core.js`). Every number below comes from those files "
             "or from `web/data/ephem.bin`. Contract: `docs/data_contract.md` section 17 (proposal).\n")
    L.append("## Why the Moon has seasons\n")
    L.append("The Moon's equator is tilted only about 1.54° to the ecliptic (Cassini's laws), so the subsolar point moves "
             f"between about {min(smin):+.2f}° and {max(smax):+.2f}° selenographic latitude in 2026–2030 (ephemeris; the extra beyond 1.54° is "
             "physical libration and the Sun's direction seen from the Moon rather than from Earth). At the equator that changes almost nothing. "
             "Near the poles the Sun skims the horizon, so a ±1.5° shift decides whether a rim or peak clears the surrounding terrain: "
             "this is the lunar season.\n")
    L.append("Extremes of the subsolar latitude after a 709 h (one lunation) running mean, which removes the small monthly wobble "
             "(minimum = southern-summer solstice, maximum = northern):\n")
    L.append("| kind | UTC date | lunation-mean subsolar latitude |\n|---|---|---|")
    for kind, j, v in sol:
        L.append(f"| Sun farthest {kind} | {(T0 + timedelta(hours=j)).strftime('%Y-%m-%d')} | {v:+.3f}° |")
    if gaps:
        L.append(f"\nSpacing of the southern-summer solstices: {', '.join(f'{g:.1f}' for g in gaps)} days (mean {np.mean(gaps):.1f} d). "
                 "The lunar seasonal cycle is shorter than an Earth year (it follows the eclipse year, about 346.6 d, because the "
                 "Moon's orbit precesses), so the polar 'best months' come earlier in the calendar every year.\n")
    L.append("## Method\n")
    L.append("- Calendar months 2026-01 … 2030-12 (UTC), 60 months tiling the 43,824 ephemeris hours exactly.\n"
             "- Per month: `core.metrics(site, i0, i1)` with hourly samples — sun = solar disc ≥ 50 % above the LOLA horizon mask, "
             "Earth = Earth centre above the mask, both = both at the same hour, longest dark = longest not-sunlit run inside the month "
             "(runs are cut at month boundaries).\n"
             "- A calendar month (28–31 d) is not a whole lunar day (29.53 d), so at the equator a 31-day month can hold one more day than "
             "night or the reverse. To separate that calendar effect from the season, each month also gets the same metrics over "
             "709 h (one synodic month) centred on the month (`lunation`). The chart draws the calendar-month bars and the lunation line.\n"
             "- 'Sun south' months = month-mean subsolar latitude ≤ −1°; 'Sun north' ≥ +1°. "
             f"{len(south)} and {len(north)} of the 60 months qualify.\n")
    L.append("## What the data shows\n")
    L.append(f"- **Equatorial and mid-latitude sites (|lat| < 30°, {len(eq)} sites): no real season.** Their lunation-averaged sunlight "
             f"changes by at most {100 * eq_span:.1f} percentage points over 5 years. The calendar-month values move more "
             f"(up to {100 * eq_cal:.1f} pp) only because months and lunar days do not line up.\n")
    for r in polar[:6]:
        L.append(f"- **{r['id']}** (lat {r['lat']:.2f}°): lunation sunlight {pct(r['lmin'])} – {pct(r['lmax'])}; "
                 f"Sun-south minus Sun-north months {100 * r['dS']:+.1f} pp; best month {r['best']} ({pct(r['bv'])}), worst {r['worst']} ({pct(r['wv'])}); "
                 f"longest dark in a month {r['dmin']}–{r['dmax']} h.")
    cs = [np.corrcoef(json.loads((DATA / "monthly" / f"{r['id']}.json").read_text())["lunation"]["sun_frac"], mid)[0, 1] for r in polar]
    ce = [np.corrcoef(e, mid)[0, 1] for r in polar
          for e in [json.loads((DATA / "monthly" / f"{r['id']}.json").read_text())["lunation"]["earth_frac"]] if np.std(e) > 0]
    L.append(f"\nAt the {len(polar)} sites south of 80°S, lunation sunlight is highest when the Sun is south of the lunar equator "
             f"(southern summer): correlation with the month-mean subsolar latitude r = {min(cs):.2f} … {max(cs):.2f}. "
             f"Earth visibility also changes from month to month at many polar sites, but it is not tied to the solar season "
             f"(r = {min(ce):.2f} … {max(ce):.2f} for the {len(ce)} sites where it varies): it depends on where Earth sits in the sky (libration), not on the Sun.\n")
    L.append("## All sites\n")
    L.append("| site | lat | lunation sun min–max | Sun south − Sun north | best month (sun; first if tied) | worst month (sun) | longest dark per month | lunation Earth min–max |")
    L.append("|---|---|---|---|---|---|---|---|")
    for r in sorted(rows, key=lambda r: r["lat"]):
        L.append(f"| {r['id']} | {r['lat']:.2f} | {pct(r['lmin'])}–{pct(r['lmax'])} | {100 * r['dS']:+.1f} pp | {r['best']} {pct(r['bv'])} | "
                 f"{r['worst']} {pct(r['wv'])} | {r['dmin']}–{r['dmax']} h | {pct(r['emin'])}–{pct(r['emax'])} |")
    L.append("\n## Verification\n")
    L.append(f"`python pipeline/verify_seasons.py` (numpy re-implementation, no core.js) → `docs/seasons_check.json`: "
             f"{'PASS' if chk['pass'] else 'FAIL'}. Random months {', '.join(chk['random_months'])} for "
             f"{', '.join(chk['sites'])}: identical hour counts and longest dark, fractions equal to 4 decimals "
             "(also for all 60 months and the lunation windows). For all 33 sites the hour-weighted 60-month mean equals "
             "`web/data/metrics/<ID>.json` (max |difference| "
             f"{max(v['max_abs_diff'] for v in chk['average_check'].values()):.1e}).\n")
    L.append("Geometry only: no atmosphere, no refraction, observer 2 m above the terrain, Earth centre criterion. "
             "Hourly sampling; a simple (unweighted) mean of the 60 monthly percentages differs slightly from the 5-year value "
             "because months have different lengths.\n")
    (ROOT / "docs" / "seasons.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/seasons.md")


if __name__ == "__main__":
    main()
